export function gerarProvinciasDePais(pais) {
  const provincias = [];
  for (const regiao of pais.regioes || []) {
    const cidadesIds = (regiao.cidades || []).map((cid) => `${pais.id}_${cid}`);
    provincias.push({
      id: `${pais.id}_${regiao.id}`,
      nome: regiao.nome,
      paisId: pais.id,
      regiaoOriginal: regiao.id,
      cidadesIds,
      cargos: [
        {
          id: `${pais.id}_${regiao.id}_governador`,
          nome: `Governador de ${regiao.nome}`,
          escopo: { nivel: "provincia", alvoId: `${pais.id}_${regiao.id}` },
          poderes: ["mudarLei", "ajustarSliders", "editarOrcamento", "nomearIG"],
          holderEmail: "",
          atribuidoPor: "",
          atribuidoEm: "",
        },
      ],
    });
  }
  return provincias;
}

export function idsProvinciasECidades(pais) {
  const provincias = gerarProvinciasDePais(pais);
  const mapa = {};
  for (const p of provincias) {
    for (const cid of p.cidadesIds) {
      mapa[cid] = p.id;
    }
  }
  return mapa;
}